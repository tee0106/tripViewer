export function errorText(lang: keyof typeof copy, code: string) {
  const s = copy[lang]
  const map: Record<string, string> = {
    permission: s.permission,
    auth: s.auth,
    api: s.api,
    missing: s.missing,
    fetch: s.fetch,
    badUrl: s.badUrl,
    popup: s.popup,
    dbRules: s.dbRules,
  }
  return map[code] || s.fetch
}
